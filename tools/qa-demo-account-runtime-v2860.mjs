import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../js/demo-account-runtime.js',import.meta.url),'utf8');
const mem=new Map();
const sessionStorage={getItem:k=>mem.has(k)?mem.get(k):null,setItem:(k,v)=>mem.set(k,String(v)),removeItem:k=>mem.delete(k)};
const location={href:'',replace(v){this.href=v;}};
const document={readyState:'loading',addEventListener(){},body:{classList:{contains(){return false;}}},getElementById(){return null;},querySelectorAll(){return[];}};
const window={dispatchEvent(){},addEventListener(){}};
const context={window,document,location,sessionStorage,Intl,Date,Math,JSON,String,Number,Object,Array,Boolean,CustomEvent:function(){},setTimeout,clearTimeout,console};
vm.createContext(context);vm.runInContext(source,context,{filename:'demo-account-runtime.js'});
let fail=0;const check=(c,m)=>{console.log(`${c?'PASS':'FAIL'} ${m}`);if(!c)fail++;};
const api=window.LDMDemoAccount;
check(Boolean(api),'API demo tersedia');
api.start('kasir');
check(location.href==='demo-app.html','start mengarah ke demo-app');
const raw=sessionStorage.getItem(api.STATE_KEY);const state=JSON.parse(raw);
check(state.profileId==='kasir','profil Kasir tersimpan');
check(state.version==='28.6.0','versi state benar');
check(state.expiresAt>state.createdAt,'TTL state aktif');
check(Array.isArray(state.products)&&state.products.length>=5,'seed produk tersedia');
check(Array.isArray(state.schedules)&&state.schedules.length>0,'seed jadwal tersedia');
check(Array.isArray(state.absences)&&state.absences.some(x=>x.storeCode==='DEMO-B'),'seed lintas cabang tersedia');
api.reset();const resetState=JSON.parse(sessionStorage.getItem(api.STATE_KEY));
check(resetState.profileId==='kasir','reset mempertahankan profil aktif');
api.exit();
check(sessionStorage.getItem(api.STATE_KEY)===null,'exit menghapus state demo');
check(location.href==='index.html','exit kembali ke login asli');
process.exitCode=fail?1:0;
