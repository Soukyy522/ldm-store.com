(function(){
  "use strict";

  const replacements=[
    [/Supabase\s+Auth/gi,"akun pengelola"],
    [/Supabase\s+Storage/gi,"penyimpanan aplikasi"],
    [/Supabase/gi,"layanan aplikasi"],
    [/License\s+Authority/gi,"layanan lisensi"],
    [/sessionStorage/gi,"penyimpanan sementara"],
    [/localStorage/gi,"penyimpanan aplikasi"],
    [/IndexedDB/gi,"penyimpanan aplikasi"],
    [/Edge\s+Functions?/gi,"layanan otomatis"],
    [/\bRPC\b/gi,"proses aplikasi"],
    [/\bRLS\b/gi,"aturan akses"],
    [/\bbackend\b/gi,"layanan utama"],
    [/\bdatabase\b/gi,"data aplikasi"],
    [/\bendpoint\b/gi,"layanan"],
    [/\bwebhook\b/gi,"notifikasi otomatis"],
    [/\bAPI\b/g,"layanan"],
    [/\bProject Ref\b/gi,"identitas layanan"],
    [/\bCORS\b/g,"akses layanan"],
    [/\borigin\b/gi,"alamat aplikasi"],
    [/\bmigration\b/gi,"pembaruan data"],
    [/\bbuild\b/gi,"versi aplikasi"],
    [/\bcache\b/gi,"data sementara"],
    [/\bPWA\b/g,"aplikasi web"],
    [/\bStack Trace\b/gi,"Rincian kejadian"],
    [/\braw error code\b/gi,"kode kendala"],
    [/\berror code\b/gi,"kode kendala"],
    [/\bsecret\b/gi,"pengaturan pengelola"],
    [/\btoken\b/gi,"kode akses"],
    [/\bdebug\b/gi,"pemeriksaan"],
    [/\bDeveloper note\b/gi,"Catatan"],
    [/\bcatatan developer\b/gi,"Catatan"],
    [/\bAI-generated\b/gi,""],
    [/\bGenerated by AI\b/gi,""],
    [/\bChatGPT\b/gi,""],
    [/\bOpenAI\b/gi,""],
    [/\bOWNER_REQUIRED\b/g,"Akses hanya untuk Owner"],
    [/\bSHIFT_TIDAK_SESUAI\b/g,"Shift tidak sesuai jadwal"],
    [/\bJADWAL_BELUM_DIATUR\b/g,"Jadwal belum diatur"]
  ];

  function cleanText(value){
    let text=String(value??"");
    for(const [pattern,replacement] of replacements) text=text.replace(pattern,replacement);
    return text.replace(/\s{2,}/g," ").replace(/\s+([,.;:!?])/g,"$1").trim();
  }

  function cleanNode(node){
    if(!node)return;
    if(node.nodeType===Node.TEXT_NODE){
      const parent=node.parentElement;
      if(parent&&/^(SCRIPT|STYLE|NOSCRIPT|TEMPLATE)$/i.test(parent.tagName))return;
      const before=node.nodeValue||"";
      const after=cleanText(before);
      if(after!==before.trim() && before.trim()) node.nodeValue=before.replace(before.trim(),after);
      return;
    }
    if(node.nodeType!==Node.ELEMENT_NODE)return;
    if(/^(SCRIPT|STYLE|NOSCRIPT|TEMPLATE)$/i.test(node.tagName))return;
    for(const attr of ["title","placeholder","aria-label"]){
      if(node.hasAttribute(attr)){
        const before=node.getAttribute(attr)||"";
        const after=cleanText(before);
        if(after!==before)node.setAttribute(attr,after);
      }
    }
    node.childNodes.forEach(cleanNode);
  }

  function run(){
    cleanNode(document.body);
    const observer=new MutationObserver(records=>{
      for(const record of records){
        if(record.type==="characterData")cleanNode(record.target);
        record.addedNodes.forEach(cleanNode);
      }
    });
    observer.observe(document.body,{subtree:true,childList:true,characterData:true});
  }

  if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",run,{once:true});
  else run();
})();
